"""Retro 2026-11-21, cloud-first runs: a cloud session starts its successor and its
Initiative's Epic sessions itself, registers itself, records a deliberate wait, and the proxy
footer with a session url is stripped."""
from datetime import timedelta

import pytest

import sdlc_next as s
from tests.test_cloud_epics import (CLOUD, FP_A, LAUNCH_OUT, NOW, FakeClaude, FakeGit, _ended,
                                    _initiative, _launched, _next, _status)
from tests.test_retro_1020_cloud import _edit_initiative


@pytest.fixture
def cloud(monkeypatch):
    monkeypatch.setenv("CLAUDE_CODE_REMOTE", "true")
    monkeypatch.setenv("CLAUDE_CODE_REMOTE_SESSION_ID", "cse_01SELF")


def test_a_cloud_session_hands_back_the_launch_instead_of_running_the_cli(cloud):
    gh, claude = _initiative(2), FakeClaude(LAUNCH_OUT)
    out = s.cmd_launch_cloud_epic(gh, 2, runner=FakeGit(), claude=claude)
    assert out["launch_in_session"] is True and out["prompt"] == "/sdlc:run 2"
    assert out["launched"] is False and claude.calls == []
    assert CLOUD in gh.issues[2]["labels"] and gh.comments_on(2) == []


def test_a_laptop_still_launches_through_the_cli():
    gh, claude = _initiative(2), FakeClaude(LAUNCH_OUT)
    out = s.cmd_launch_cloud_epic(gh, 2, runner=FakeGit(), claude=claude)
    assert out["launched"] is True and len(claude.calls) == 1


def _settled_overlap_tree():
    return _initiative(
        {"number": 2, "labels": ["type:epic", CLOUD], "body": FP_A,
         "comments": [_launched(), _ended(outcome="context-reset")]},
        {"number": 3, "labels": ["type:epic", CLOUD], "body": FP_A,
         "comments": [_launched("session_01BBB"), _ended("session_01BBB", outcome="stopped")]})


def test_relaunch_ignores_an_overlapping_epic_whose_session_ended():
    out = s.cmd_launch_cloud_epic(_settled_overlap_tree(), 2, relaunch=True, runner=FakeGit(),
                                  claude=FakeClaude(LAUNCH_OUT))
    assert out["launched"] is True


def test_a_first_launch_still_waits_on_an_overlapping_ended_epic():
    gh = _settled_overlap_tree()
    gh.issues[2]["comments"] = []
    out = s.cmd_launch_cloud_epic(gh, 2, runner=FakeGit(), claude=FakeClaude(LAUNCH_OUT))
    assert out["refused"] is True and "overlaps #3" in out["reason"]


def test_record_cloud_session_self_registers_this_session(cloud):
    gh = _initiative(2)
    out = s.cmd_record_cloud_session(gh, 2, None)
    assert out["recorded"] is True and out["session"]["id"] == "session_01SELF"
    assert s.cmd_record_cloud_session(gh, 2, None)["already_recorded"] is True


def test_record_cloud_session_self_fails_outside_a_cloud_session():
    with pytest.raises(s.GhError, match="CLAUDE_CODE_REMOTE_SESSION_ID"):
        s.cmd_record_cloud_session(_initiative(2), 2, None)


def test_an_initiative_holds_its_own_session_markers(cloud):
    gh = _initiative(2)
    assert s.cmd_record_cloud_session(gh, 1, None)["recorded"] is True
    assert _status(gh, 1)["session"]["id"] == "session_01SELF"
    assert s.cmd_end_cloud_session(gh, 1, "stopped")["ended"] is True
    with pytest.raises(s.GhError, match="not an Epic or Initiative"):
        gh.issues[7] = {**gh.issues[2], "number": 7, "labels": ["type:task"], "parent": 2}
        s.cmd_end_cloud_session(gh, 7, "stopped")


def _initiative_in_cloud(monkeypatch):
    monkeypatch.setitem(s.PIPELINE["placement"], "initiativeEpics", "cloud")
    gh = _initiative(2)
    gh.issues[1]["labels"].append(CLOUD)
    return gh


def test_a_cloud_initiative_run_launches_its_epics_sessions(monkeypatch, cloud):
    gh = _initiative_in_cloud(monkeypatch)
    out = _next(gh)
    assert out["action"] == "launch-cloud-epics" and out["epics"] == [2]


def test_a_laptop_initiative_run_still_launches_cloud_epics(monkeypatch):
    gh = _initiative_in_cloud(monkeypatch)
    gh.issues[1]["labels"].remove(CLOUD)
    assert _next(gh)["action"] == "launch-cloud-epics"


def test_a_waiting_heartbeat_is_not_a_stall_until_the_longer_bound():
    gh = _edit_initiative({"number": 2, "labels": ["type:epic", CLOUD],
                           "comments": [_launched(minutes=300)]})
    s.cmd_cloud_heartbeat(gh, 2, "waiting", now=NOW - timedelta(minutes=120))
    row = _status(gh)["epics"][0]
    assert row["stalled"] is False and row["session"]["state"] == "waiting"
    # Positive control: the same silence while `working` is a stall.
    s.cmd_cloud_heartbeat(gh, 2, "working", now=NOW - timedelta(minutes=120), force=True)
    assert _status(gh)["epics"][0]["stalled"] is True


def test_the_proxy_footer_with_a_session_url_is_stripped():
    footer = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code/session_013Fm-x)_\n"
    assert s.strip_proxy_footer("body\n\n<!-- sdlc:ci-local -->" + footer).endswith("-->")
    plain = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
    assert s.strip_proxy_footer("body" + plain) == "body"


def test_self_registration_never_takes_a_local_unit_with_work_in_progress(cloud):
    gh = _initiative(2, extra=[{"number": 5, "labels": ["type:task"], "parent": 2,
                                "status": "in-progress"}])
    out = s.cmd_record_cloud_session(gh, 2, None)
    assert out["refused"] is True and out["in_progress"] == [5]
    assert CLOUD not in gh.issues[2]["labels"]
    # Positive control: the operator placed it, so the session registers.
    gh.issues[2]["labels"].append(CLOUD)
    assert s.cmd_record_cloud_session(gh, 2, None)["recorded"] is True
