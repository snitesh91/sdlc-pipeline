def test_set_stage_maps_the_config_field_to_its_numeric_id_and_the_slug_to_the_option_name():
    gh, runner = _gh({("POST", f"{R}/issues/7/issue-field-values"): {}})
    gh.set_stage_field(7, "pr-review")
    gh.set_pipeline_status_field(7, "awaiting-human-review")
    gh.set_priority_field(7, "Urgent")
    gh.set_effort_field(7, "Low")
    assert [c[2] for c in runner.writes()] == [
        [("-F", "issue_field_values[][field_id]=11"), ("-f", "issue_field_values[][value]=PR Review")],
        [("-F", "issue_field_values[][field_id]=12"),
         ("-f", "issue_field_values[][value]=Awaiting Human Review")],
        [("-F", "issue_field_values[][field_id]=13"), ("-f", "issue_field_values[][value]=Urgent")],
        [("-F", "issue_field_values[][field_id]=14"), ("-f", "issue_field_values[][value]=Low")],
    ]
    # The org's fields are listed once per provider, not once per write.
    assert sum(1 for c in runner.calls if c[1] == "orgs/owner/issue-fields") == 1


