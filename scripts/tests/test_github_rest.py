class Pages:
    """A multi-page response for `RestRunner`: page N is `pages[N-1]`, later pages `empty`."""

    def __init__(self, pages: list, empty=None):
        self.pages, self.empty = pages, ([] if empty is None else empty)


class RestRunner:
    """Fake `gh api`: canned JSON per (method, path); `--paginate --jq` emits one compact
    line per item like gh. Records `(method, path, fields)`; anything unscripted fails."""

    def __init__(self, routes: dict):
        self.routes = dict(routes)
        self.calls: list = []

    def __call__(self, argv):
        assert argv[:2] == ["gh", "api"], f"not a REST call: {argv}"
        assert "graphql" not in argv, f"GraphQL reached the REST provider: {argv}"
        args, method, jq, fields = argv[2:], "GET", None, []
        path = None
        i = 0
        while i < len(args):
            a = args[i]
            if a == "-X":
                method, i = args[i + 1], i + 2
            elif a == "--jq":
                jq, i = args[i + 1], i + 2
            elif a in ("-f", "-F"):
                fields.append((a, args[i + 1]))
                i += 2
            elif a == "--paginate":
                i += 1
            else:
                path, i = a, i + 1
        if fields and method == "GET":
            method = "POST"
        assert not path.startswith("repositories/"), f"numeric-id path: {path}"
        page = None
        m = re.search(r"[?&]page=(\d+)$", path)
        if m:  # `_api_items` paging: route on the path without `page`/the default per_page
            page, path = int(m.group(1)), path[:m.start()]
            if (method, path) not in self.routes and path.endswith("per_page=100"):
                path = path[:-len("per_page=100")].rstrip("?&")
        self.calls.append((method, path, fields))
        key = (method, path)
        if key not in self.routes:
            raise AssertionError(f"unscripted gh api call: {key} {fields}")
        resp = self.routes[key]
        if page is not None:  # a scripted list is one page; a list of pages is `Pages`
            if isinstance(resp, Pages):
                resp = resp.pages[page - 1] if page <= len(resp.pages) else resp.empty
            elif page > 1:
                resp = [] if isinstance(resp, list) else {k: ([] if isinstance(v, list) else v)
                                                           for k, v in resp.items()}
        if isinstance(resp, Exception):
            raise resp
        if jq is None:
            return json.dumps(resp) if resp is not None else ""
        if jq.endswith("[]"):
            items = resp if jq == ".[]" else resp[jq[1:-2]]
            return "".join(json.dumps(x) + "\n" for x in items)
        return f"{resp[jq[1:]]}\n"

    def writes(self):
        return [c for c in self.calls if c[0] != "GET"]


def _issue(n, **kw):
    return {"number": n, "id": 9000 + n, "node_id": f"I_{n}", "title": f"issue {n}",
            "body": "", "state": "open", "created_at": "2026-08-01T00:00:00Z",
            "labels": [], "type": None, "issue_field_values": [], "milestone": None,
            "parent_issue_url": None, "pull_request": None, **kw}


def _fv(field_id, name, option):
    return {"issue_field_id": field_id, "data_type": "single_select", "issue_field_name": name,
            "value": 1, "single_select_option": {"id": 1, "name": option}}


def _gh(routes):
    runner = RestRunner({("GET", "orgs/owner/issue-fields"): ORG_FIELDS, **routes})
    return GitHubRest(runner=runner), runner


