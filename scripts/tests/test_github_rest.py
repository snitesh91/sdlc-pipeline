def _pr(n, **kw):
    return {"number": n, "title": f"pr {n}", "state": "open", "merged_at": None, "draft": True,
            "body": "", "created_at": "2026-08-05T00:00:00Z", "html_url": f"https://x/pull/{n}",
            "head": {"ref": "issue-9", "sha": "abc123"}, "base": {"ref": "epic-5"},
            "merge_commit_sha": "test-merge-sha", **kw}


