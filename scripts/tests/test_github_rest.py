def test_every_graphql_or_gh_subcommand_method_is_overridden():
    # A GitHub method left on GraphQL or `gh issue|pr|label` would 403 behind the cloud proxy.
    # `_set_single_select` is reached only through the overridden `set_*_field` methods.
    leaky = []
    for name, fn in inspect.getmembers(GitHub, inspect.isfunction):
        src = inspect.getsource(fn)
        uses = ("self.graphql(" in src or '"gh", "issue"' in src or '"gh", "pr"' in src
                or '"gh", "label"' in src or '"gh", "run", "rerun"' in src)
        if uses and name not in GitHubRest.__dict__ and name != "_set_single_select":
            leaky.append(name)
    assert leaky == []


